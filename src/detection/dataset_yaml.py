"""Generate the Ultralytics ``data.yaml`` that points YOLO at the built dataset.

Kept as generated code rather than a checked-in static file because the class
list lives in ``config.CLASSES`` and the two must never disagree -- a mismatch
between the ids baked into the label files and the names in ``data.yaml``
produces a model that trains happily and reports the wrong class forever.

The ``path`` entry is written as an absolute or caller-supplied root so the same
generator works locally and on Colab, where the dataset is unzipped somewhere
else entirely.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from src import config


def build_yaml(root: str | Path | None = None) -> str:
    """Return the YAML text describing the dataset.

    Args:
        root: dataset root containing ``images/`` and ``labels/``.  Defaults to
            ``data/processed`` inside the repo.

    Returns:
        YAML document as a string.
    """
    root = Path(root) if root is not None else config.PROCESSED_DIR
    names = "\n".join(f"  {i}: {name}" for i, name in enumerate(config.CLASSES))
    return (
        "# Generated by src/detection/dataset_yaml.py -- do not edit by hand.\n"
        "# Class ids must stay in sync with src/config.py:CLASSES.\n"
        f"path: {root}\n"
        "train: images/train\n"
        "val: images/val\n"
        "test: images/test\n"
        f"nc: {config.NUM_CLASSES}\n"
        "names:\n"
        f"{names}\n"
    )


def write_yaml(out_path: str | Path | None = None, root: str | Path | None = None) -> Path:
    """Write ``data.yaml`` and return the path written."""
    out_path = Path(out_path) if out_path else config.PROCESSED_DIR / "data.yaml"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build_yaml(root))
    return out_path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=None)
    parser.add_argument("--root", default=None)
    args = parser.parse_args()
    print(write_yaml(args.out, args.root))
